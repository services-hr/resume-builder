export default async function handler(req, res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") return res.status(200).end();
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed" });

  const { type, text, context } = req.body;

  if (!type || !text) {
    return res.status(400).json({ error: "type and text are required" });
  }

  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    return res.status(500).json({ error: "ANTHROPIC_API_KEY is not configured" });
  }

  // プロンプトと検索ツール有無を決定
  let prompt;
  let useWebSearch = false;

  if (type === "career") {
    // すべての経歴でWeb検索＋フォーマット適用
    prompt = buildCurrentCareerPrompt(text, context);
    useWebSearch = true;
  } else if (type === "skills") {
    prompt = buildSkillsPrompt(text);
  } else if (type === "pr") {
    prompt = buildPrPrompt(text);
  } else {
    return res.status(400).json({ error: `Unknown type: ${type}` });
  }

  // リクエストボディ組み立て
  const requestBody = {
    model: "claude-sonnet-4-20250514",
    max_tokens: useWebSearch ? 2500 : 1200,
    messages: [{ role: "user", content: prompt }],
  };

  // Web検索ツールを有効化（career全体）
  if (useWebSearch) {
    requestBody.tools = [
      {
        type: "web_search_20250305",
        name: "web_search",
        max_uses: 1,
      },
    ];
  }

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": apiKey,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify(requestBody),
    });

    const data = await response.json();

    if (!response.ok) {
      console.error("Anthropic API error:", data);
      return res.status(response.status).json({ error: "AI API error", details: data });
    }

    // テキストブロックだけを連結（tool_use や tool_result ブロックは除外）
    const result = (data.content || [])
      .filter((b) => b.type === "text")
      .map((b) => b.text || "")
      .join("")
      .trim();

    return res.status(200).json({ result });
  } catch (error) {
    console.error("Server error:", error);
    return res.status(500).json({ error: "Internal server error" });
  }
}
